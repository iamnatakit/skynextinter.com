function openLightbox(src, caption) {
    const modal = document.getElementById('sn-lightbox');
    const img = document.getElementById('sn-lightbox-img');
    const cap = document.getElementById('sn-lightbox-caption');
    img.src = src;
    cap.textContent = caption;
    modal.style.display = 'flex';
}

function closeLightbox(e) {
    if (e.target.id === 'sn-lightbox' || e.target.tagName === 'BUTTON') {
        document.getElementById('sn-lightbox').style.display = 'none';
    }
}

document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape') {
        const modal = document.getElementById('sn-lightbox');
        if (modal) modal.style.display = 'none';
    }
});
